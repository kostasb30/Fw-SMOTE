// Δομή δεδομένων
//Ορίζει ένα αντικείμενο που περιέχει ένα διάνυσμα με τα χαρακτηριστικά (features) και έναν ακέραιο για την ετικέτα της κλάσης (label)
struct Sample {
    vector<double> features;
    int label; // 0: Πλειοψηφία, 1: Μειοψηφία
};

// 1. Υπολογισμός IMOWA Weights (βάσει του paper)
// Υλοποιεί τον operator IMOWA
// Η γραμμή pow((double)i / n, p_owa) - pow((double)(i - 1) / n, p_owa) υπολογίζει τα βάρη 
// έτσι ώστε τα χαρακτηριστικά με την υψηλότερη κατάταξη να παίρνουν αναλογικά πολύ μεγαλύτερη αξία.
vector<double> getIMOWAWeights(int n, double p_owa) {
    vector<double> weights(n);
    for (int i = 1; i <= n; ++i) {
        // Τύπος: w_i = (i/n)^p - ((i-1)/n)^p
        weights[i-1] = pow((double)i / n, p_owa) - pow((double)(i - 1) / n, p_owa);
    }
    return weights;
}

// 2. Σταθμισμένη Minkowski Απόσταση - Εδώ υπολογίζεται η απόσταση μεταξύ δύο δειγμάτων
// Αντί για απλή απόσταση, κάθε διαφορά abs(s1.features[i] - s2.features[i]) πολλαπλασιάζεται με το βάρος w[i] που προέκυψε από την IMOWA.
// Αν pmink​=2, έχουμε τη γνωστή Ευκλείδεια απόσταση, αλλά "ζυγισμένη" ανάλογα με τη σημασία κάθε χαρακτηριστικού.
//Η pow (power) χρησιμοποιείται για να υψώσει έναν αριθμό σε μια δύναμη.
// Βάση: Είναι το dist, δηλαδή το άθροισμα που υπολογίστηκε προηγουμένως στο for loop.
// Εκθέτης: Είναι το 1.0 / p_mink
double weightedMinkowski(const Sample& s1, const Sample& s2, const vector<double>& w, double p_mink) {
    double dist = 0.0;
    for (size_t i = 0; i < s1.features.size(); ++i) {
        dist += w[i] * pow(abs(s1.features[i] - s2.features[i]), p_mink);
    }
    return pow(dist, 1.0 / p_mink); 
}

// 3. Υπολογισμός Relief Scores (Inducing Variables)
// calculateReliefScores: Αυτή η συνάρτηση "βαθμολογεί" κάθε χαρακτηριστικό.
// Επιλέγει ένα τυχαίο δείγμα (targetIdx).
// Βρίσκει τον πιο κοντινό γείτονα της ίδιας κλάσης (nearHit) και τον πιο κοντινό της διαφορετικής κλάσης (nearMiss).
// Αν σε ένα χαρακτηριστικό το δείγμα διαφέρει πολύ από τον "εχθρό" (diffMiss) αλλά μοιάζει με τον "φίλο" (diffHit), 
// τότε αυτό το χαρακτηριστικό είναι καλό για να ξεχωρίζουμε τις κλάσεις και παίρνει υψηλό σκορ.
// Ο Relief λειτουργεί επιλέγοντας τυχαία δείγματα και συγκρίνοντάς τα με τους κοντινότερους γείτονές τους (Hit και Miss). Όσο περισσότερες επαναλήψεις (iterations) κάνεις, 
// τόσο πιο σταθερά και αξιόπιστα θα είναι τα scores των χαρακτηριστικών σου (αυθαίρετα ορίζω τις επαναλήψεις ως 100)
vector<double> calculateReliefScores(const vector<Sample>& data, int iterations = 100) {
    int nF = data[0].features.size(); // Παίρνει το πλήθος των χαρακτηριστικών (features) από το πρώτο δείγμα
    vector<double> scores(nF, 0.0);  // Δημιουργεί ένα διάνυσμα που θα αποθηκεύσει το "σκορ" κάθε χαρακτηριστικού. Αρχικά όλα είναι 0.0.
    
    for (int it = 0; it < iterations; ++it) { // ο αλγόριθμος θα επανάβει την διαδικασία 100 φορές που ορίσαμε το iterations
        int targetIdx = rand() % data.size(); // επιλέγει τυχαία με τη rand ένα δείγμα από το σύνολο δεδομένων
        int nearHit = -1, nearMiss = -1;      //ο κοντινότερος γείτονας που ανήκει στην ίδια κλάση με το near Hit, nearMiss ο κοντινότερος γείτονας που ανήκει σε διαφορετική κλάση
        double minHitDist = 1e18, minMissDist = 1e18; // μια πολύ μεγάλη τιμή για να ξεκινήσει η σύγκριση των αποστάσεων

        for (int i = 0; i < data.size(); ++i) {
            if (i == targetIdx) continue; // μην συγκρίνεις το δείγμα με τον εαυτό του
            double d = 0; // Απλή Ευκλείδεια απόσταση για το Relief
            for(int f=0; f<nF; f++) d += pow(data[targetIdx].features[f] - data[i].features[f], 2); // Εδώ υπολογίζεται η Ευκλείδια απόσταση στο τετράγωνο ανάμεσα στο τυχαίο δειγμά και σε ολα τα άλλα δείγματα της λίστας 
            
            if (data[i].label == data[targetIdx].label) { // Αν το δείγμα i έχει το ίδιο label
                if (d < minHitDist) { minHitDist = d; nearHit = i; } // ελέγχουμε αν είναι το πιο κοντινό (nearHit).
            } else { //// Αν έχει διαφορετικό label
                if (d < minMissDist) { minMissDist = d; nearMiss = i; } // ελέγχουμε αν είναι το πιο κοντινό (nearMiss).
            }
        }
        // Ενημέρωση των scores
        // Εδώ ελέγχουμε ποιο χαρακτηριστικό f είναι χρήσιμο
        // Στην αρχή της επανάληψης, ορίσαμε nearHit = -1 και nearMiss = -1. Το -1 είναι μια τιμή "σημαία" (flag) που σημαίνει: «δεν έχω βρει ακόμα τίποτα».
        if (nearHit != -1 && nearMiss != -1) { // Προχώρησε στον υπολογισμό των scores μόνο αν βρήκες τουλάχιστον έναν "φίλο" (Near Hit) και έναν "εχθρό" (Near Miss)».
            for (int f = 0; f < nF; ++f) {
                double diffHit = abs(data[targetIdx].features[f] - data[nearHit].features[f]); // Πόσο διαφέρει το χαρακτηριστικό f από τον "όμοιο" γείτονα. Θέλουμε αυτή η διαφορά να είναι μικρή.
                double diffMiss = abs(data[targetIdx].features[f] - data[nearMiss].features[f]); // Πόσο διαφέρει από τον "διαφορετικό" γείτονα. Θέλουμε αυτή η διαφορά να είναι μεγάλη.
                scores[f] += (diffMiss - diffHit); // Αν ένα χαρακτηριστικό έχει μεγάλη διαφορά με τον "εχθρό" (Miss) και μικρή με τον "φίλο" (Hit), το score του αυξάνεται. Αυτό σημαίνει ότι είναι ένα καλό χαρακτηριστικό για να ξεχωρίζουμε τις κλάσεις.
            }
        }
    }
    return scores; // επιστρέφει τη λίστα με τα τελικά score
}

// 4. Κύρια συνάρτηση FW-SMOTE, θα επιστρέψει μια λίστα διανυσμάτων που περιέχει τα νέα τεχνητά δείγματα που δημιούργησε
// Παίρνει 5 ορίσματα : const Vector<Sample> - το αρχικό σύνολο δεδομένων, int k - ο αριθμός των κοντινότερων γειτόνων - ο αλγόριθμος θα ψάξει να βρεί τον αριθμό των κοντινότερων γειτόνων για κάθε δειγμα
// int numToGenerate - Πόσα ακριβώς νέα τεχνητά δείγματα θέλεις να φτιάξει η συνάρτηση
// double p_owa - μια παράμετρος για τον υπολογισμό των βαρών (order weighted averaging). Καθορίζει πόσα ¨δυνατά" θα πριμοδοτηθούν τα σημαντικά χαρακτηριστικά ένταντι των λιγότερο
// double p_mink - Η παράμετρος για την απόσταση Minkowski, αν p_mink = 2 ο αλγοριθμός χρησιμοποιεί την κλασσική Ευκλείδια Απόσταση
vector<Sample> FW_SMOTE(const vector<Sample>& data, int k, int numToGenerate, double p_owa, double p_mink) {
    int nF = data[0].features.size(); // στην μεταβλητή nF- (from number of features) βάζουμε το μέγεθος των χαρακτηριστικών του πρώτου δείγματος
    // αυτή η πρώτη γραμμή είναι σημαντική γιατί ο αλγόριθμος πρέπει να ξέρει πόσες στήλες έχει το dataset. 

    // Α. Relief Scores
    vector<double> scores = calculateReliefScores(data); // καλεί την συνάρτηση calculateReliefScores και αποθηκεύει το αποτέλεσμα στο διάνυσμα scores

    // Β. Induced Order (IMOWA)
    // Αν ταξινομούσαμε μόνο τα scores, θα χάναμε την πληροφορία για το ποιο χαρακτηριστικό ανήκει σε κάθε score. Με το pair, το score μένει "κολλημένο" με τον αριθμό της στήλης του.
    vector<pair<double, int>> ranked; // Δημιουργεί μια λίστα από ζευγάρια.Double - πόσο καλό είναι το χαρακτηριστικό. Int - ποιο χαρακτηριστικό είναι.
    for(int i=0; i<nF; i++) ranked.push_back({scores[i], i}); // γεμίζει τη λίστα ranked.
    // Παράδειγμα: Αν το scores είναι [0.2, 0.8, 0.5], μετά από αυτό το loop το ranked θα είναι:
    //{{0.2, 0}, {0.8, 1}, {0.5, 2}}

    // rbegin() και rend() (Reverse): Στη C++, η απλή sort ταξινομεί από το μικρότερο στο μεγαλύτερο. 
    // Χρησιμοποιώντας το r (reverse), η ταξινόμηση γίνεται φθίνουσα (από το μεγαλύτερο στο μικρότερο).
    // Τα χαρακτηριστικά με το μεγαλύτερο score μπαίνουν πρώτα στη λίστα.
    // Με βάση το παράδειγμα: {{0.8, 1}, {0.5, 2}, {0.2, 0}}
    // Στον αλγόριθμο IMOWA (Induced Matrix Ordered Weighted Averaging), η σειρά των χαρακτηριστικών καθορίζει ποιο βάρος θα πάρει το καθένα. 
    // Το χαρακτηριστικό που ήρθε "πρώτο" (αυτό με το 0.8 στο παράδειγμά μας) θα πάρει το μεγαλύτερο βάρος κατά τη δημιουργία των νέων δειγμάτων.

    sort(ranked.rbegin(), ranked.rend()); // η sort ταξινομεί τα ζευγάρια.

    
    // Τι κάνει: Καλεί μια βοηθητική συνάρτηση που παράγει μια λίστα από μαθηματικά βάρη (q1​,q2​,…,qn​).
    // Η λογική: Αυτά τα βάρη είναι συνήθως φθίνοντα (δηλαδή το πρώτο είναι το μεγαλύτερο και το τελευταίο το μικρότερο).
    // Παράδειγμα: Αν έχουμε 3 χαρακτηριστικά, το q μπορεί να είναι [0.7, 0.2, 0.1]. 
    // Αυτά τα νούμερα λένε: "Ο 1ος θα πάρει το 70%, ο 2ος το 20% και ο 3ος το 10% της σημασίας".
    
    // Τι κάνει: Καλεί μια βοηθητική συνάρτηση που παράγει μια λίστα από μαθηματικά βάρη (q1​,q2​,…,qn​).
    // Η λογική: Αυτά τα βάρη είναι συνήθως φθίνοντα (δηλαδή το πρώτο είναι το μεγαλύτερο και το τελευταίο το μικρότερο).
    // Παράδειγμα: Αν έχουμε 3 χαρακτηριστικά, το q μπορεί να είναι [0.7, 0.2, 0.1]. Αυτά τα νούμερα λένε: "Ο 1ος θα πάρει το 70%, ο 2ος το 20% και ο 3ος το 10% της σημασίας".

    vector<double> q = getIMOWAWeights(nF, p_owa);
    vector<double> finalWeights(nF); // Δημιουργεί ένα νέο, άδειο διάνυσμα με μέγεθος nF (όσα και τα χαρακτηριστικά μας).
    // το ranked έχει τα χαρακτηριστικά ταξινομημένα από το καλύτερο στο χειρότερο
    // Είναι ο αρχικός αριθμός (index) του χαρακτηριστικού.
    // Είναι το βάρος που αντιστοιχεί στην i-οστή θέση κατάταξης

    //Αν το πιο σημαντικό χαρακτηριστικό ήταν το "Χαρακτηριστικό 2" (ranked[0].second = 2):
    //Για i=0: Το finalWeights[2] θα πάρει την τιμή q[0] (το μεγαλύτερο βάρος).
    // Έτσι, το βάρος "δένεται" με το σωστό χαρακτηριστικό στην αρχική του θέση.
    for(int i=0; i<nF; i++) {
        finalWeights[ranked[i].second] = q[i];
    }
    // Γ. Διαχωρισμός μειοψηφίας
    // Αυτό το τμήμα κώδικα απομονώνει μόνο τα δείγματα που ανήκουν στην μειοψηφία για να δουλέψει ο SMOTE μόνο με αυτά
    vector<Sample> minority; // Δημιουργεί μια άδεια λίστα διανυσμάτων για να μπούνε τα μειοψηφικά
    // range-based for loop
    // Διαβάζει ένα-προς-ένα όλα τα δείγματα (s) που υπάρχουν μέσα στο αρχικό διάνυσμα data
    for(const auto& s : data) {
        // αν η ετικέτα label του κάθε δείγματος είναι 1 τότε βάλτο στην λίστα της μειοψηφίας
        // Στα προβλήματα δυαδικής ταξινόμησης (binary classification), συνήθως το 1 συμβολίζει τη σπάνια κλάση (μειοψηφία) και το 0 τη συνηθισμένη (πλειοψηφία)
        if(s.label == 1) minority.push_back(s);
    }
    // Δ. Παραγωγή δειγμάτων
    // Επειδή ο SMOTE δημιουργεί νέα δεδομένα, χρειάζεται μια γεννήτρια που να παράγει τυχαίους αριθμούς
    // Σκοπός να αποθηκεύονται ένα-προς-ένα τα νέα τεχνητά δείγματα που δημιουργεί ο αλγόριθμος.
    vector<Sample> synthetic; // Δημιουργεί ένα άδειο διάνυσμα με το όνομα Synthetic
    mt19937 gen(time(0)); // Παράγει ψευδοτυχαίους αριθμούς..Αλγόριθμος marsenne Twister - gen το ονομα που δίνουμε στη γεννήτρια - Είναι το λεγόμενο Seed (time) -
    // Χρησιμοποιούμε την ώρα του συστήματος ώστε κάθε φορά που τρέχει το πρόγραμμα η γεννήτρια να ξεκινά από διαφορετικό σημείο
    
    // Λέει στον υπολογιστή ότι θέλουμε δεκαδικούς αριθμούς (double) και ότι κάθε αριθμός στο εύρος που θα ορίσουμε έχει την ίδια ακριβώς πιθανότητα να εμφανιστεί (ομοιόμορφη κατανομή).
    uniform_real_distribution<> dis(0, 1);
    
    // ειναι ο κεντρικός βρόχος της διαδικασίας και θα επαναληφθεί όσο ορίσαμε την παράμετρο numToGenerate
    for (int i = 0; i < numToGenerate; ++i) {
        // Επιλέγει έναν τυχαίο αριθμό που αντιστοιχεί σε μια θέση (index) μέσα στη λίστα των μειοψηφικών δειγμάτων.
        // Η rand() δίνει έναν μεγάλο τυχαίο ακέραιο.
        //Το % (modulo - υπόλοιπο διαίρεσης) με το minority.size() περιορίζει αυτόν τον αριθμό από το 0 έως το μέγεθος_της_λίστας - 1.

        int idx = rand() % minority.size(); 
        // Δημιουργεί μια αναφορά (alias) στο τυχαίο δείγμα που μόλις επιλέξαμε και το ονομάζει target
        // Το target είναι το κεντρικό σημείο αναφοράς μας για αυτή την επανάληψη. 
        // Ο SMOTE θα ψάξει τώρα να βρει τους γείτονες αυτού του συγκεκριμένου δείγματος για να γεννήσει ένα νέο ανάμεσά τους
        const auto& target = minority[idx]; 

        // Weighted k-NN
        // Δημιουργεί μια προσωρινή λίστα από ζευγάρια
        //Κάθε ζευγάρι θα αποθηκεύει:
        //Την απόσταση (double) του δείγματος j από το target.
        //Τον δείκτη/θέση (int) του δείγματος j στη λίστα minority.
        //Χρειαζόμαστε και την απόσταση (για να ξέρουμε ποιος είναι κοντά) και το index (για να ξέρουμε ποιος είναι αυτός ο γείτονας).
        vector<pair<double, int>> neighbors;
        // ενα loop που διατρέχει όλα τα δείγματα της μειοψηφίας
        // Πρέπει να μετρήσουμε την απόσταση του target από κάθε άλλο μέλος της ίδιας ομάδας.
        for(int j=0; j<minority.size(); j++) {

            //Αν το τρέχον δείγμα j είναι το ίδιο με το target (δηλαδή έχουν το ίδιο index), μην υπολογίσεις απόσταση. Πήγαινε στο επόμενο". 
            // Δεν έχει νόημα να μετρήσουμε την απόσταση ενός σημείου από τον εαυτό του (θα ήταν 0).
            if(idx == j) continue;

            //Καλεί τη συνάρτηση που είδαμε στην αρχή. Υπολογίζει την απόσταση λαμβάνοντας υπόψη τα βάρη (finalWeights) που βγάλαμε από τον Relief. 
            //Έτσι, η απόσταση "μετράει" περισσότερο τις διαφορές στα σημαντικά χαρακτηριστικά.
            //push_back: Βάζει το ζευγάρι {απόσταση, index} μέσα στη λίστα neighbors.
            neighbors.push_back({weightedMinkowski(target, minority[j], finalWeights, p_mink), j});
        }

        // Ταξινομεί τη λίστα των γειτόνων
        // Από προεπιλογή, η sort στα pairs κοιτάζει το πρώτο στοιχείο. Εδώ, το πρώτο στοιχείο είναι η απόσταση.
        // Τα δείγματα με τη μικρότερη απόσταση (οι πιο κοντινοί γείτονες) μπαίνουν στις πρώτες θέσεις της λίστας.

        // Έστω ότι το target είναι το δείγμα Νο 4. Ο κώδικας υπολογίζει αποστάσεις και η λίστα neighbors γίνεται:

        // {12.5, 0} (Το δείγμα 0 απέχει 12.5)

        // {2.1, 1}  (Το δείγμα 1 απέχει 2.1)

        // {5.8, 2}  (Το δείγμα 2 απέχει 5.8)

        // Μετά τη sort, η λίστα γίνεται:

        // {2.1, 1} -> Ο πιο κοντινός γείτονας!

        // {5.8, 2}

        // {12.5, 0}

        // Τώρα ο αλγόριθμος ξέρει ότι ο δείκτης 1 είναι ο καλύτερος "φίλος" του target και μπορεί να γεννήσει ένα νέο δείγμα ανάμεσά τους.
        sort(neighbors.begin(), neighbors.end());

        // Επιλογή τυχαίου γείτονα από τους k καλύτερους
        // Ο SMOTE κανονικά κοιτάζει τους k κοντινότερους γείτονες. Αν όμως η μειοψηφία σου είναι πολύ μικρή (π.χ. έχεις μόνο 3 δείγματα συνολικά) και το k σου είναι 5,
        // η min διασφαλίζει ότι δεν θα ψάξεις για γείτονες που δεν υπάρχουν. Θα πάρει το μικρότερο από τα δύο.
        // rand() % ...: Επιλέγει έναν τυχαίο αριθμό από το 0 έως το k−1. Έτσι, δεν διαλέγουμε πάντα τον πρώτο (τον πιο κοντινό) γείτονα, αλλά έναν από τους k καλύτερους. 
        // neighbors[...]: Πηγαίνει στη θέση που επέλεξε η rand() μέσα στη λίστα των ταξινομημένων γειτόνων.
        // .second: Όπως είδαμε πριν, το .first είναι η απόσταση και το .second είναι το index (η θέση) του δείγματος στη λίστα minority. Αποθηκεύουμε λοιπόν αυτό το index στη μεταβλητή neighborIdx.
        // Τώρα που ξέρουμε τη θέση (neighborIdx), πάμε στη λίστα minority και "τραβάμε" ολόκληρο το αντικείμενο Sample που αντιστοιχεί σε αυτή τη θέση.

        //Τώρα έχουμε στα χέρια μας δύο δείγματα: το target (το αρχικό) και τον neighbor (τον τυχαίο γείτονα). Το νέο μας δείγμα θα γεννηθεί κάπου "στο δρόμο" ανάμεσα σε αυτούς τους δύο.
        // Παράδειγμα:

        // Αν k=5, ο κώδικας θα διαλέξει στην τύχη έναν από τους 5 πιο κοντινούς γείτονες. Έστω ότι η rand() διαλέγει τον 2ο κοντινότερο. Ο κώδικας παίρνει το index του 2ου γείτονα και μας δίνει πρόσβαση στα δεδομένα του (π.χ. τις μετρήσεις του).
        const auto& neighbor = minority[neighborIdx];

        Sample sNew; // Δημιουργεί ένα νέο, κενό αντικείμενο τύπου Sample με το όνομα sNew
        sNew.label = 1; // Του δίνει αμέσως την ετικέτα της μειοψηφίας
        //Παράγει έναν τυχαίο δεκαδικό αριθμό μεταξύ 0.0 και 1.0.

        // Σκοπός: Το gap (κενό/απόσταση) καθορίζει το σημείο πάνω στη νοητή γραμμή μεταξύ target και neighbor όπου θα τοποθετηθεί το νέο δείγμα.

        // Αν gap = 0.5, το νέο δείγμα θα είναι ακριβώς στη μέση.

        // Αν gap = 0.1, θα είναι πολύ κοντά στον "γονέα" (target).
        double gap = dis(gen);
        // βρόχος για κάθε ένα από τα χαρακτηριστικά του δείγματος
        /* Αυτός είναι ο μαθηματικός τύπος της παρεμβολής:

           (neighbor.features[f] - target.features[f]): Υπολογίζει τη διαφορά (απόσταση) μεταξύ των δύο δειγμάτων για το συγκεκριμένο χαρακτηριστικό f.

            gap * ...: Παίρνει ένα τυχαίο ποσοστό αυτής της διαφοράς.

            target.features[f] + ...: Προσθέτει αυτό το ποσοστό στην αρχική τιμή του target.

            push_back: Αποθηκεύει το αποτέλεσμα στο διάνυσμα των χαρακτηριστικών του sNew.
        */
        for(int f=0; f<nF; f++) {
            sNew.features.push_back(target.features[f] + gap * (neighbor.features[f] - target.features[f]));
        }

        /*Τώρα που το sNew είναι έτοιμο (έχει label και όλα τα features του), το προσθέτει στη λίστα synthetic. 
          Αυτή η λίστα μεγαλώνει σε κάθε επανάληψη του μεγάλου for loop.
        */
        synthetic.push_back(sNew);
    }
    /*Αφού ολοκληρωθούν όλες οι επαναλήψεις (δηλαδή φτιάχτηκαν όλα τα δείγματα που ζητήθηκαν), 
      η συνάρτηση επιστρέφει ολόκληρη τη λίστα με τα τεχνητά δεδομένα πίσω στο σημείο που την κάλεσε (π.χ. στη main).
    */
    return synthetic;
}

int main() {
    // είναι αυτή που εξασφαλίζει ότι το πρόγραμμά θα παράγει διαφορετικούς τυχαίους αριθμούς κάθε φορά που εκτελείται
    srand(time(0));

    // Παράδειγμα: 5 δείγματα (2 μειοψηφία, 3 πλειοψηφία)
    vector<Sample> dataset = {
        {{0.1, 0.1, 0.1}, 1}, {{0.15, 0.12, 0.11}, 1}, // Μειοψηφία
        {{0.9, 0.8, 0.9}, 0}, {{0.85, 0.88, 0.82}, 0}, {{0.7, 0.75, 0.8}, 0} // Πλειοψηφία
    };

    // Παράμετροι εισόδου FW-SMOTE
    /* Με k = 2, 
     ο αλγόριθμος θα επιλέγει τυχαία έναν από τους 2 πιο κοντινούς γείτονες του αρχικού δείγματος για να κάνει την παρεμβολή.
    */
    int k = 2;  // Ορίζει τον αριθμό των κοντινότερων γειτόνων
    int n_synthetic = 3; // Ορίζει πόσα νέα τεχνητά δείγματα θέλεις να δημιουργήσεις
    /*
    Ελέγχει την "αυστηρότητα" της απόδοσης των βαρών (IMOWA).

    Σημασία: Αυτή η παράμετρος καθορίζει πόσο μεγάλη διαφορά θα έχουν τα βάρη μεταξύ των σημαντικών και των λιγότερο σημαντικών χαρακτηριστικών.

    Με μεγαλύτερες τιμές, ο αλγόριθμος δίνει πολύ μεγάλη έμφαση στα χαρακτηριστικά που βγήκαν πρώτα στην κατάταξη του Relief και αγνοεί σχεδόν τελείως τα υπόλοιπα.
    */
    double p_owa = 2.0;    // IMOWA focus
    /*
      Ορίζει τον τύπο της γεωμετρικής απόστασης που θα χρησιμοποιηθεί.

      Σημασία: * Αν p_mink = 2.0, χρησιμοποιείται η Ευκλείδεια απόσταση (η κλασική απόσταση σε ευθεία γραμμή, όπως το Πυθαγόρειο Θεώρημα).

      Αν p_mink = 1.0, χρησιμοποιείται η απόσταση Manhattan (σαν να κινείσαι σε τετράγωνα πόλης).
    */
    double p_mink = 2.0;   

    /*

    Η κλήση της συνάρτησης FW_SMOTE

    Τα ορίσματα :

    Dataset: Τα αρχικά δεδομένα.

    k: Τον αριθμό των γειτόνων (που ορίσαμε ως 2).

    n_synthetic: Πόσα δείγματα θέλουμε (που ορίσαμε ως 3).

    p_owa & p_mink: Τις μαθηματικές ρυθμίσεις.

    result : αποθηκεύουμε εδώ σ αυτό το διάνυσμα
    */    
    vector<Sample> result = FW_SMOTE(dataset, k, n_synthetic, p_owa, p_mink); // 

    cout << "Synthesized Samples:" << endl; // Εκτυπώνει τον τίτλο Synthsized Samples και αλλάζει γραμμή
    // ο βρόχος τρέχει όλα τα δείγματα που βρίσκονται αποθηκευμένα στο result
    // το s ειναι το τρέχων δείγμα σε κάθε επανάληψη και χρησιμοποιούμε αναφορά & για ταχύτητα
    for (const auto& s : result) {
        // Εκτυπώνει τη λέξη features στην αρχή κάθε γραμμής, για να ξέρουμε ότι αυτά που ακολουθούν είναι τα χαρακτηριστικά του δείγματος.
        cout << "features: ";
        /*
        Για το συγκεκριμένο δείγμα s, παίρνει κάθε αριθμό (double f) που υπάρχει στη λίστα των χαρακτηριστικών του (features) και τον εκτυπώνει, αφήνοντας ένα κενό ανάμεσα.

        Αποτέλεσμα: Αν ένα δείγμα έχει χαρακτηριστικά [10.2, 24.0], θα εκτυπωθεί: 10.2 24.0 .
        */
        for(double f : s.features) cout << f << " ";
        // Αφού τελειώσει η εκτύπωση όλων των χαρακτηριστικών, προσθέτει μια κάθετο |, γράφει τη λέξη "label:" και εκτυπώνει την κλάση του δείγματος (που για τον SMOTE είναι πάντα 1).
        cout << "| label: " << s.label << endl;
    }
    
    return 0;
}
